import { useState, type FormEvent } from 'react'
import Icon from '../../components/Icon'
import Modal from '../../components/Modal'
import { Field, FormGrid, btnPrimary, btnSecondary, inputCls } from '../../components/Form'
import { FAQ_AUDIENCES, FAQ_CATEGORIES } from '../../lib/constants'
import { supabase } from '../../lib/supabase'
import type { FaqCategory } from '../../lib/types'
import { CATEGORY_ICON, type Audience, type FaqWithStaff } from './shared'

const CATEGORY_KEYS = Object.keys(FAQ_CATEGORIES) as FaqCategory[]

/** Create (faq === 'new') or edit a FAQ. Code (FAQ-xxx) is generated by the DB on insert. */
export function FaqFormModal({ faq, meId, onClose, onSaved }: { faq: FaqWithStaff | 'new' | null; meId: string | null; onClose: () => void; onSaved: (msg: string) => void }) {
  return (
    <Modal open={faq !== null} title={faq === 'new' ? 'Thêm câu hỏi FAQ mới' : faq ? `Chỉnh sửa #${faq.code}` : ''} onClose={onClose}
      footer={
        faq !== null && (
          <>
            <button type="button" className={btnSecondary} onClick={onClose}>Hủy bỏ</button>
            <button type="submit" form="faq-form" className={btnPrimary}>
              <Icon name={faq === 'new' ? 'add_circle' : 'save'} className="text-[20px]" />
              {faq === 'new' ? 'Thêm câu hỏi' : 'Lưu thay đổi'}
            </button>
          </>
        )
      }>
      {faq !== null && <FaqForm key={faq === 'new' ? 'new' : faq.id} faq={faq} meId={meId} onSaved={onSaved} />}
    </Modal>
  )
}

function FaqForm({ faq, meId, onSaved }: { faq: FaqWithStaff | 'new'; meId: string | null; onSaved: (msg: string) => void }) {
  const existing = faq === 'new' ? null : faq
  const [f, setF] = useState({
    category: (existing?.category ?? 'operations') as FaqCategory,
    audience: (existing?.audience ?? 'all') as Audience,
    question: existing?.question ?? '',
    answer: existing?.answer ?? '',
    is_visible: existing?.is_visible ?? true,
  })
  const [saving, setSaving] = useState(false)
  const [err, setErr] = useState<string | null>(null)

  async function submit(e: FormEvent) {
    e.preventDefault()
    if (saving) return
    setSaving(true)
    setErr(null)
    const payload = {
      category: f.category,
      audience: f.audience,
      question: f.question.trim(),
      answer: f.answer.trim(),
      is_visible: f.is_visible,
      icon: existing && existing.category === f.category ? existing.icon : CATEGORY_ICON[f.category].icon,
      updated_by_id: meId,
      updated_at: new Date().toISOString(),
    }
    const { error } = existing ? await supabase.from('faqs').update(payload).eq('id', existing.id) : await supabase.from('faqs').insert(payload)
    setSaving(false)
    if (error) return setErr(error.message)
    onSaved(existing ? `Đã lưu #${existing.code}` : 'Đã thêm câu hỏi FAQ mới')
  }

  return (
    <form id="faq-form" onSubmit={submit}>
      <FormGrid>
        <Field label="Chuyên mục">
          <select className={inputCls} value={f.category} onChange={(e) => setF({ ...f, category: e.target.value as FaqCategory })}>
            {CATEGORY_KEYS.map((k) => <option key={k} value={k}>{FAQ_CATEGORIES[k]}</option>)}
          </select>
        </Field>
        <Field label="Đối tượng hiển thị">
          <select className={inputCls} value={f.audience} onChange={(e) => setF({ ...f, audience: e.target.value as Audience })}>
            {(Object.keys(FAQ_AUDIENCES) as Audience[]).map((k) => <option key={k} value={k}>{FAQ_AUDIENCES[k]}</option>)}
          </select>
        </Field>
        <Field label="Câu hỏi" required className="sm:col-span-2">
          <input required className={inputCls} value={f.question} onChange={(e) => setF({ ...f, question: e.target.value })} placeholder="Ví dụ: Làm thế nào để đối soát doanh thu?" />
        </Field>
        <Field label="Câu trả lời" required className="sm:col-span-2">
          <textarea required rows={5} className={inputCls} value={f.answer} onChange={(e) => setF({ ...f, answer: e.target.value })} placeholder="Nhập nội dung hướng dẫn cho Merchant..." />
        </Field>
        <label className="flex min-h-[40px] cursor-pointer items-center gap-2 text-[14px] font-semibold text-on-surface sm:col-span-2">
          <input type="checkbox" className="h-4 w-4 accent-primary-container" checked={f.is_visible} onChange={(e) => setF({ ...f, is_visible: e.target.checked })} />
          Hiển thị cho Merchant
        </label>
        {err && <p className="rounded-lg bg-error-container px-3 py-2 text-[13px] text-on-error-container sm:col-span-2">{err}</p>}
      </FormGrid>
    </form>
  )
}
